function getNestedValue(obj, key) {
  return key.split('.').reduce((result, part) => (result && result[part] != null ? result[part] : null), obj)
}

export function LanguageProvider({ children }) {
  const [locale, setLocale] = useState(() => localStorage.getItem(STORAGE_KEY) || defaultLang)

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale)
  }, [locale])

  const t = useMemo(() => {
    return (key) => {
      const value = getNestedValue(translations[locale] || translations[defaultLang], key)
      if (value != null) return value
      const fallback = getNestedValue(translations[defaultLang], key)
      return fallback != null ? fallback : key
    }
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t, languages }), [locale, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext)
}

export function translate(key) {
  const locale = localStorage.getItem(STORAGE_KEY) || defaultLang
  const value = getNestedValue(translations[locale] || translations[defaultLang], key)
  if (value != null) return value
  return getNestedValue(translations[defaultLang], key) || key
}
